"""Deal stage and deal brief for the overview (revamp, 15 Oct; DECISIONS 15 Oct 19:00).

The stage is worked out from the documents in the deal, not typed in: what the paperwork shows exists. A person may
override it (the CRM knows things the documents don't, such as a shortlist); an override is shown as one. Each open
gap is placed at the stage of the earliest document its promise was quoted from, so the page can say where promises
that the paperwork doesn't back were first made. Reads only; nothing here changes a finding.

The deal brief (summary, key deliverables) is written and confirmed by the deal owner, never generated by the model,
so it adds no unverified model text. Demo briefs live in data/profiles/<deal>.json; deals without one show none.
"""

import json

import config
import ledger_fixes

STAGES = [
    ("discovery", "Discovery"),
    ("evaluation", "Evaluation"),
    ("proposal", "Proposal / RFP"),
    ("shortlisted", "Shortlisted"),
    ("contracting", "Contracting"),
    ("signed", "Signed"),
    ("handover", "Handover"),
]
STAGE_INDEX = {key: n for n, (key, _) in enumerate(STAGES)}
STAGE_NOTES = {
    "contracting": "Last point to fix gaps cheaply",
    "signed": "Promises lock",
    "handover": "Snapshot frozen for Delivery",
}

# Document types that mark a stage. Calls are special: the first call is Discovery, later calls Evaluation.
# Types that say nothing about the stage (the internal pricing note, customer emails) sit at the stage reached by
# their date and never move the deal forward on their own.
DOC_STAGE = {
    "rfp_response": "proposal",
    "proposal": "proposal",
    "security_questionnaire": "evaluation",
    "draft_sow": "contracting",
    "draft_contract": "contracting",
    "signed_sow": "signed",
    "signed_contract": "signed",
}
PROFILE_DIR = config.ROOT / "data" / "profiles"


def _docs(conn, did: int) -> list:
    """Included documents, latest version of each, oldest first: (source_key, doc_type, doc_date, label)."""
    rows = conn.execute(
        "SELECT s.source_key, v.doc_type, v.doc_date, s.display_name FROM sources s JOIN source_versions v"
        " ON v.source_id = s.id WHERE s.deal_id = ? AND v.included = 1 AND v.version_no ="
        " (SELECT MAX(version_no) FROM source_versions WHERE source_id = s.id) ORDER BY v.doc_date, s.source_key",
        (did,)).fetchall()
    return [{"key": k, "type": t, "date": d or "", "file": f} for k, t, d, f in rows]


def place_documents(docs: list) -> dict:
    """source_key -> stage key, following DOC_STAGE and the call rule; docs must be oldest first."""
    placed, reached, seen_call = {}, "discovery", False
    for d in docs:
        if d["type"] == "call_transcript":
            stage = "evaluation" if seen_call else "discovery"
            seen_call = True
        else:
            stage = DOC_STAGE.get(d["type"])
        if stage and STAGE_INDEX[stage] > STAGE_INDEX[reached]:
            reached = stage
        placed[d["key"]] = reached  # a document never sits before the stage the deal had already reached
    return placed


def load_profile(slug: str) -> dict:
    path = PROFILE_DIR / f"{slug}.json"
    if not ledger_fixes.USER_SLUG.fullmatch(slug) and path.is_file():
        return json.loads(path.read_text(encoding="utf-8"))
    return {}


def _gap_sources(conn, did: int) -> list:
    """For each promise with an open gap, the source keys its open issues' stored claims quote it from (v2 only).
    Counted per promise, not per finding, so the bar matches the promises listed below it."""
    import handover  # 16 Oct: a gap resolved by a current note is not counted as open anywhere
    noted = handover.note_resolved_ids(conn, did)
    by_promise = {}
    for iid, cid, criteria_json in conn.execute(
            "SELECT i.id, i.commitment_id, i.closure_criteria FROM issues i JOIN issue_current_state s ON s.issue_id = i.id"
            " JOIN commitments c ON c.id = i.commitment_id WHERE c.deal_id = ? AND s.state <> 'Resolved'", (did,)):
        if iid in noted:
            continue
        claim = (json.loads(criteria_json or "{}") or {}).get("claim") or {}
        keys = [q["source_id"] for q in claim.get("promise_quotes") or [] if q.get("source_id")]
        if keys:
            by_promise.setdefault(cid, []).extend(keys)
    return list(by_promise.values())


def deal_stage(conn, slug: str) -> dict:
    """The stage bar: each stage with its documents and the open gaps first promised there, the current stage, and
    whether it comes from the documents or from a person's override."""
    did = ledger_fixes.deal_id(conn, slug)
    docs = _docs(conn, did)
    placed = place_documents(docs)
    reached = max((placed[d["key"]] for d in docs), key=STAGE_INDEX.get, default=None)
    profile = load_profile(slug)
    override = profile.get("stage_override") or {}
    current, basis = reached, "documents"
    if override.get("stage") in STAGE_INDEX:
        current, basis = override["stage"], "override"
    import handover  # 16 Oct: a signature recorded by a person moves the deal to Signed (the pipeline reads drafts only)
    signed = handover.signature(conn, did)
    if signed and (current is None or STAGE_INDEX[current] < STAGE_INDEX["signed"]):
        current, basis = "signed", "signature"

    order = {d["key"]: n for n, d in enumerate(docs)}
    started = {}
    for keys in _gap_sources(conn, did):
        known = [k for k in keys if k in order]
        if known:
            first = min(known, key=order.get)
            started[placed[first]] = started.get(placed[first], 0) + 1

    from workspace import DOC_TYPE_LABELS  # screen names by type only: no key or file name ever reaches a response
    import handover
    links = handover.links(conn, did)
    stages = []
    for key, label in STAGES:
        stages.append({
            "key": key, "label": label,
            "documents": [{"name": DOC_TYPE_LABELS.get(d["type"], d["type"]), "date": d["date"], "link": links.get(d["key"])}
                          for d in docs if placed[d["key"]] == key],
            "gaps_started": started.get(key, 0),
            "state": ("none" if current is None else "done" if STAGE_INDEX[key] < STAGE_INDEX[current]
                      else "current" if key == current else "todo"),
            "note": STAGE_NOTES.get(key, ""),
        })
    total = sum(started.values())
    top = max(started, key=started.get) if started else None
    headline = ""
    if top:
        name = dict(STAGES)[top]
        headline = (f"All {total} promises with open gaps were first made at {name}" if started[top] == total and total > 1
                    else f"{started[top]} of {total} promises with open gaps were first made at {name}" if total > 1
                    else f"The promise with an open gap was first made at {name}")
    return {"current": current, "current_label": dict(STAGES).get(current, "No documents yet"), "basis": basis,
            "signature": signed,
            "override": override if basis == "override" else None, "stages": stages, "headline": headline}


def deal_brief(conn, slug: str) -> dict | None:
    """The owner-confirmed summary and deliverables, or None when the deal has none. Like a decision, a brief is
    confirmed against one document version: when a newer version of that document arrives, the brief is shown as
    needing re-confirmation, never silently as current (15 Oct, after the simulated Delivery review)."""
    p = load_profile(slug)
    if not p.get("summary"):
        return None
    stale, stale_note = False, ""
    basis = p.get("confirmed_against") or {}
    if basis.get("source"):
        did = ledger_fixes.deal_id(conn, slug)
        row = conn.execute(
            "SELECT MAX(v.version_no), (SELECT v2.doc_type FROM source_versions v2 WHERE v2.source_id = s.id ORDER BY"
            " v2.version_no DESC LIMIT 1) FROM sources s JOIN source_versions v ON v.source_id = s.id"
            " WHERE s.deal_id = ? AND s.source_key = ?", (did, basis["source"])).fetchone()
        latest, dtype = (row or (None, None))
        if latest and latest > int(basis.get("version") or 1):
            from workspace import DOC_TYPE_LABELS
            name = DOC_TYPE_LABELS.get(dtype, "source document")
            stale = True
            stale_note = (f"Confirmed against {name} version {basis.get('version') or 1}; version {latest} has arrived since. "
                          "The deal owner should reconfirm this brief.")
    return {"summary": p["summary"], "deliverables": list(p.get("deliverables") or []),
            "confirmed_by": p.get("confirmed_by") or "", "basis": p.get("basis") or "", "go_live": p.get("go_live") or "",
            "needs_reconfirmation": stale, "reconfirm_note": stale_note}
